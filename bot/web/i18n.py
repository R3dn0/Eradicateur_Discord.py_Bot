def get_web_locale(request: Request) -> str:
    """Resolve current locale from cookie or query param."""
    # 1. Query param override (?lang=fr / ?lang=en)
    query_lang = request.query_params.get("lang")
    if query_lang in AVAILABLE_LOCALES:
        return query_lang

    # 2. Cookie
    cookie_lang = request.cookies.get("dashboard_lang")
    if cookie_lang in AVAILABLE_LOCALES:
        return cookie_lang

    return DEFAULT_LOCALE


def translate_web(key: str, locale: str = DEFAULT_LOCALE, default: str | None = None, **kwargs: Any) -> Markup:
    """Translate a web dictionary key."""
    catalog = WEB_TRANSLATIONS.get(locale) or WEB_TRANSLATIONS[DEFAULT_LOCALE]
    text = catalog.get(key)
    if text is None:
        # Fallback to English catalog
        text = WEB_TRANSLATIONS["en"].get(key)
    if text is None:
        text = default or key

    if kwargs:
        try:
            return Markup(text.format(**kwargs))
        except Exception:
            return Markup(text)
    return Markup(text)
